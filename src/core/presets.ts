export function getPreset(id = "red_magic_cross"): Project {
  const preset = PRESETS.find((p) => p.id === id);
  if (!preset)
    throw new Error(
      `Unknown preset ${id}. Use vfx presets to list available effects.`,
    );
  return structuredClone(preset.project);
}
